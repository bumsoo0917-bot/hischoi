function buildLesson(lessonId:number):Question[]{
  const facts=rows[lessonId];
  const ref=official[lessonId];
  return facts.flatMap(([term,clue,distinction,page],index)=>{
    const wrong=[1,6,11].map(offset=>facts[(index+offset)%facts.length]);
    const common={
      lessonId,
      concept:term,
      page:`PDF ${page}쪽`,
      noteUrl:`/notes/pdf-${page}.pdf`,
      source:`최태성 별별한국사 강의 필기 PDF ${page}쪽`,
      sourceUrl:ref.url,
      explanation:`정답은 ‘${term}’이다. ${clue} 혼동 방지: ${distinction}`,
    };
    return [
      {...common,id:`l${lessonId}-q${index+1}-a`,level:1 as const,prompt:`다음 설명이 직접 가리키는 개념은 무엇인가?\n\n${clue}`,choices:[term,...wrong.map(item=>item[0])],answer:term},
      {...common,id:`l${lessonId}-q${index+1}-b`,level:1 as const,prompt:`${lessonId}강 필기의 다음 핵심 단서와 정확히 연결되는 항목을 고르시오.\n\n${clue}`,choices:[term,...wrong.map(item=>item[0])],answer:term},
      {...common,id:`l${lessonId}-q${index+1}-c`,level:2 as const,prompt:`다음 중 ‘${term}’ 자체에 대한 설명으로 옳은 것은?`,choices:[clue,...wrong.map(item=>item[1])],answer:clue},
      {...common,id:`l${lessonId}-q${index+1}-d`,level:2 as const,prompt:`[자료]\n${clue}\n\n자료의 내용과 직접 연결되는 개념은 무엇인가?`,choices:[term,...wrong.map(item=>item[0])],answer:term},
      {...common,id:`l${lessonId}-q${index+1}-e`,level:3 as const,prompt:`‘${term}’을 비슷한 개념과 구별하는 기준으로 가장 적절한 것은?`,choices:[distinction,...wrong.map(item=>item[2])],answer:distinction},
    ];
  });
}

export const laterQuestions:Question[]=Object.keys(rows).flatMap(id=>buildLesson(Number(id)));
