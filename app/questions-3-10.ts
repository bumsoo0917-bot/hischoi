function buildLesson(lessonId:number):Question[]{
  const {facts,pages}=rows[lessonId];
  const ref=official[lessonId];
  return facts.flatMap(([term,clue],index)=>{
    const wrong=[1,3,7].map(offset=>facts[(index+offset)%facts.length]);
    const page=pages[index%pages.length];
    const common={lessonId,concept:term,page:`PDF ${page}쪽`,noteUrl:`/notes/pdf-${page}.pdf`,source:`최태성 별별한국사 강의 필기 PDF ${page}쪽`,sourceUrl:ref.url,explanation:`${clue} 필기의 시대·국가 범위 안에서 이 단서를 다른 유사 개념과 구별해야 한다.`};
    return [
      {...common,id:`l${lessonId}-q${index+1}-a`,level:1 as const,prompt:`${lessonId}강의 시대와 국가를 기준으로, 다음 설명에 해당하는 것은?\n\n${clue}`,choices:[term,...wrong.map(x=>x[0])],answer:term},
      {...common,id:`l${lessonId}-q${index+1}-b`,level:1 as const,prompt:`${lessonId}강 필기에서 ‘${clue}’라는 단서로 확인할 수 있는 대상을 고르시오.`,choices:[term,...wrong.map(x=>x[0])],answer:term},
      {...common,id:`l${lessonId}-q${index+1}-c`,level:2 as const,prompt:`${lessonId}강에서 다루는 사건·제도·문화유산 가운데 ‘${term}’에 대한 설명으로 옳은 것은?`,choices:[clue,...wrong.map(x=>x[1])],answer:clue},
      {...common,id:`l${lessonId}-q${index+1}-d`,level:2 as const,prompt:`[자료] ${clue}\n\n${lessonId}강의 범위에서 이 자료와 직접 연결되는 항목은?`,choices:[term,...wrong.map(x=>x[0])],answer:term},
      {...common,id:`l${lessonId}-q${index+1}-e`,level:3 as const,prompt:`다음 중 ${lessonId}강의 시대·국가 범위에서 ‘${term}’만을 정확히 설명한 것은?`,choices:[clue,...wrong.map(x=>x[1])],answer:clue},
    ];
  });
}
export const extendedQuestions:Question[]=Object.keys(rows).flatMap(id=>buildLesson(Number(id)));
