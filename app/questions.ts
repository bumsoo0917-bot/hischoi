function build(lessonId:number,facts:Fact[]):Question[]{
  return facts.flatMap((fact,index)=>{
    const wrong=[1,2,3].map(n=>facts[(index+n)%facts.length]);
    const common={lessonId,concept:fact.term,explanation:fact.clue};
    return [
      {...common,id:`${lessonId}-1-${fact.id}`,level:1 as const,prompt:`${fact.clue}\n이 설명에 해당하는 것은?`,choices:[fact.term,...wrong.map(x=>x.term)],answer:fact.term},
      {...common,id:`${lessonId}-2-${fact.id}`,level:2 as const,prompt:`‘${fact.term}’에 대한 설명으로 옳은 것은?`,choices:[fact.clue,...wrong.map(x=>x.clue)],answer:fact.clue},
      {...common,id:`${lessonId}-3-${fact.id}`,level:3 as const,prompt:`[자료]\n${fact.scenario}\n\n자료와 가장 관련 깊은 것은?`,choices:[fact.term,...wrong.map(x=>x.term)],answer:fact.term},
      {...common,id:`${lessonId}-4-${fact.id}`,level:4 as const,prompt:`‘${fact.term}’을 바르게 분석한 내용은?`,choices:[fact.advanced,...wrong.map(x=>x.advanced)],answer:fact.advanced},
    ];
  });
}
